import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'
import { extractCodes, isRecord, renderCodes } from './errorCodes.ts'

const PIN = new URL('../tests/skill/devices.openapi.json', import.meta.url)
const TYPES = new URL('../tests/skill/devices.openapi.generated.ts', import.meta.url)
const CODES = new URL('../src/api/codes.generated.ts', import.meta.url)

const HEADER = `// Generated by scripts/genDevices.ts from tests/skill/devices.openapi.json.
// Do not edit by hand: run \`bun run gen:devices <openapi.json>\` after the API's device paths change.
`

// Action paths sit under /systems/{system}/actions/ and name a real system; the pin keeps only the
// fixed device paths, which name none, so the public repository carries no system.
const isDevicePath = (path: string): boolean =>
  path.startsWith('/v1/devices') && !path.includes('/actions/')

const refsIn = (value: unknown): string[] => {
  if (Array.isArray(value)) return value.flatMap(refsIn)
  if (!isRecord(value)) return []
  const own =
    typeof value.$ref === 'string' ? [value.$ref.replace('#/components/schemas/', '')] : []
  return [...own, ...Object.values(value).flatMap(refsIn)]
}

/**
 * The device part of a system's OpenAPI document: the device paths and every schema they reach.
 * Takes a full document from `GET /v1/systems/{system}/openapi.json` or the device part alone.
 */
export const extractDevices = (document: unknown): Record<string, unknown> => {
  const paths = isRecord(document) && isRecord(document.paths) ? document.paths : {}
  const components = isRecord(document) ? document.components : undefined
  const schemas = isRecord(components) && isRecord(components.schemas) ? components.schemas : {}
  const devicePaths = Object.fromEntries(
    Object.entries(paths).filter(([path]) => isDevicePath(path)),
  )
  if (Object.keys(devicePaths).length === 0) throw new Error('The document has no device paths')
  const reached = new Set<string>()
  const pending = refsIn(devicePaths)
  while (pending.length > 0) {
    const name = pending.pop() ?? ''
    if (reached.has(name)) continue
    if (!(name in schemas)) throw new Error(`The document refers to a missing schema ${name}`)
    reached.add(name)
    pending.push(...refsIn(schemas[name]))
  }
  return {
    openapi: '3.1.0',
    info: { title: 'Deepdock devices', version: '1' },
    paths: devicePaths,
    components: {
      schemas: Object.fromEntries([...reached].sort().map((name) => [name, schemas[name]])),
    },
  }
}

const main = async (): Promise<void> => {
  const source = process.argv[2]
  if (!source) throw new Error('Usage: bun run gen:devices <path to a local openapi.json>')
  const pin = extractDevices(JSON.parse(await readFile(source, 'utf8')))
  writeFileSync(PIN, `${JSON.stringify(pin, null, 2)}\n`)
  const ast = await openapiTS(PIN)
  writeFileSync(TYPES, `${HEADER}\n${astToString(ast)}`)
  writeFileSync(CODES, renderCodes(extractCodes(pin)))
  execFileSync(
    'biome',
    ['format', '--write', ...[PIN, TYPES, CODES].map((file) => fileURLToPath(file))],
    {
      stdio: 'inherit',
    },
  )
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  main().catch((error: unknown) => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
    process.exitCode = 1
  })
}
